#!/usr/bin/env node
// Build ESA's static files and its small fallback for routes requiring HTTP logic.
import { execFileSync } from 'node:child_process';
import { copyFileSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
const aasaPath = '.well-known/apple-app-site-association';
const images = new Set(['.avif', '.gif', '.ico', '.jpeg', '.jpg', '.png', '.svg', '.webp']);
const fonts = new Set(['.otf', '.ttf', '.woff', '.woff2']);
const rootFiles = new Set(['manifest.json', 'robots.txt', 'sitemap.xml']);
const isPublic = name => name === aasaPath || rootFiles.has(name)
  || (!name.includes('/') && /\.(html|css|js)$/.test(name))
  || (name.startsWith('assets/img/') && images.has(extname(name).toLowerCase()))
  || (name.startsWith('assets/fonts/') && fonts.has(extname(name).toLowerCase()))
  || name === 'assets/fonts/playfair-display-OFL.txt';
const files = tracked.filter(isPublic);

for (const name of [...files, '_headers']) {
  if (!tracked.includes(name) || !/^[A-Za-z0-9._/-]+$/.test(name)
      || name.split('/').some(part => part === '.' || part === '..')) {
    throw new Error(`Unsafe or untracked source: ${name}`);
  }
  let source = root;
  for (const part of name.split('/')) {
    source = join(source, part);
    if (lstatSync(source).isSymbolicLink()) throw new Error(`Symlinks are not published: ${name}`);
  }
  if (!lstatSync(source).isFile()) throw new Error(`Not a regular source file: ${name}`);
}
for (const name of ['index.html', 'privacy.html', '404.html', aasaPath]) {
  if (!files.includes(name)) throw new Error(`Required public file is missing: ${name}`);
}

const read = name => readFileSync(join(root, name), 'utf8');
const content = { home: read('index.html'), privacy: read('privacy.html'), notFound: read('404.html'), aasa: JSON.parse(read(aasaPath)) };
const headers = {};
let globalSection = false;
for (const line of read('_headers').split(/\r?\n/)) {
  if (!line.trim() || line.trimStart().startsWith('#')) continue;
  if (!/^\s/.test(line)) { globalSection = line.trim() === '/*'; continue; }
  if (globalSection) {
    const colon = line.indexOf(':');
    if (colon < 1) throw new Error('Invalid global response header');
    headers[line.slice(0, colon).trim()] = line.slice(colon + 1).trim();
  }
}

// Only clear our fixed generated directories, never tracked files or symlinks.
const marker = join(root, 'build', '.oqracam-generated');
const markerStat = lstatSync(marker, { throwIfNoEntry: false });
const generated = markerStat?.isFile() && !markerStat.isSymbolicLink() && readFileSync(marker, 'utf8') === 'ESA website build\n';
for (const directory of ['dist', 'build']) {
  if (tracked.some(name => name === directory || name.startsWith(`${directory}/`))) {
    throw new Error(`Refusing to clear tracked output directory: ${directory}`);
  }
  const target = join(root, directory);
  const stat = lstatSync(target, { throwIfNoEntry: false });
  if (stat && (!stat.isDirectory() || stat.isSymbolicLink()
      || (!generated && readdirSync(target).length))) {
    throw new Error(`Refusing to clear non-generated output directory: ${directory}`);
  }
}
for (const directory of ['dist', 'build']) {
  rmSync(join(root, directory), { recursive: true, force: true });
  mkdirSync(join(root, directory));
}
writeFileSync(marker, 'ESA website build\n');

const staticFiles = files.filter(name => name !== aasaPath);
for (const name of staticFiles) {
  const target = join(root, 'dist', name);
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(join(root, name), target);
}

const entry = `// Generated by scripts/build-site.mjs. Static assets are served before this fallback.
const content = ${JSON.stringify(content)};
const headers = ${JSON.stringify(headers)};
export default {
  async fetch(request) {
    const send = (body, status = 200, extra = {}) => new Response(request.method === 'HEAD' ? null : body, {
      status, headers: { ...headers, 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-cache', ...extra }
    });
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return send('Method Not Allowed\\n', 405, { Allow: 'GET, HEAD', 'Content-Type': 'text/plain; charset=utf-8' });
    }
    const path = new URL(request.url).pathname;
    if (path === ${JSON.stringify('/' + aasaPath)}) {
      return send(JSON.stringify(content.aasa), 200, { 'Content-Type': 'application/json', 'Cache-Control': 'public, max-age=3600' });
    }
    if (path === '/support' || path === '/support/') return send(null, 302, { Location: '/#support' });
    if (path === '/' || path === '/index.html' || path.startsWith('/p/')) return send(content.home);
    if (path === '/privacy' || path === '/privacy/' || path === '/privacy.html') return send(content.privacy);
    return send(content.notFound, 404);
  }
};
`;
writeFileSync(join(root, 'build', 'esa-entry.js'), entry);
const size = staticFiles.reduce((total, name) => total + lstatSync(join(root, name)).size, 0);
console.log(`Built ${staticFiles.length} static files (${size.toLocaleString('en-US')} bytes) and one ${Buffer.byteLength(entry).toLocaleString('en-US')}-byte ESA function.`);
